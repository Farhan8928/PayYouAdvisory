/**
 * Turns the hand-supplied hero stills into responsive WebP.
 *
 * Run with `npm run hero`. Reads every `public/images/hero-slide-*.jpg`,
 * writes 960 / 1600 / 2400px WebP beside it, and emits
 * `src/data/heroImages.gen.js` carrying the intrinsic size and a blur
 * placeholder for each.
 *
 * ── Why this exists ────────────────────────────────────────────────────────
 * The stills arrived as ~700 kB JPEGs rendered by a bare `<img>` with no
 * width, no height, no srcset and no loading hint. That is four separate
 * problems in one tag: a guaranteed layout shift as the image lands, the
 * desktop file served to a 360px phone, and roughly 2.8 MB of hero imagery on
 * a connection that may be a train in Chinchwad. `npm run audit:images`
 * failed the build over it, correctly.
 *
 * The Unsplash photography already goes through `scripts/fetch-images.mjs` and
 * comes out the other side with all of this handled. These stills are not
 * fetched from anywhere, so they need their own pass — but the output shape is
 * deliberately identical, so `components/Photo.jsx` and the hero can treat
 * both the same way.
 *
 * ── The blur placeholder ───────────────────────────────────────────────────
 * A 20px-wide WebP inlined as a data URI, painted as a CSS background beneath
 * the real file. Combined with the width/height attributes it means the hero
 * reserves its exact box before anything downloads, so nothing on the page
 * moves. On a slow connection the reader sees a soft blue impression of the
 * photograph rather than a black rectangle.
 */
import { readdir, writeFile, readFile } from 'node:fs/promises'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = join(ROOT, 'public', 'images')

/** The widths actually served. 2400 covers a 1440px band on a 2x display. */
const WIDTHS = [960, 1600, 2400]

async function main() {
  const files = (await readdir(DIR))
    .filter((f) => /^hero-slide-\d+\.jpg$/i.test(f))
    .sort()

  if (!files.length) {
    console.log('\nno hero stills found in public/images — nothing to do\n')
    return
  }

  const manifest = {}

  for (const file of files) {
    const id = basename(file, '.jpg')
    const src = join(DIR, file)
    const input = await readFile(src)
    const meta = await sharp(input).metadata()

    for (const w of WIDTHS) {
      // `withoutEnlargement` so a small source is never upscaled into a file
      // larger than the original that also looks worse.
      const out = await sharp(input)
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 78 })
        .toBuffer()
      await writeFile(join(DIR, `${id}-${w}.webp`), out)
    }

    const lqip = await sharp(input).resize({ width: 20 }).webp({ quality: 40 }).toBuffer()

    manifest[id] = {
      width: meta.width,
      height: meta.height,
      // The largest derivative is the `src`, so a browser with no srcset
      // support still gets a WebP rather than the untouched JPEG.
      src: `/images/${id}-${WIDTHS[WIDTHS.length - 1]}.webp`,
      srcSet: WIDTHS.map((w) => `/images/${id}-${w}.webp ${w}w`).join(', '),
      lqip: `data:image/webp;base64,${lqip.toString('base64')}`,
    }

    const kb = (n) => `${Math.round(n / 1024)} kB`
    console.log(`  ${id}  ${meta.width}x${meta.height}  ${kb(input.length)} → webp x${WIDTHS.length}`)
  }

  const body = `/**
 * Generated by \`npm run hero\` — do not edit.
 *
 * Responsive derivatives of the hand-supplied hero stills in public/images.
 * Regenerate after replacing any hero-slide-*.jpg.
 */
export const HERO_IMAGES = ${JSON.stringify(manifest, null, 2)}
`
  await writeFile(join(ROOT, 'src', 'data', 'heroImages.gen.js'), body, 'utf8')
  console.log(`\n✓ ${files.length} hero still(s) processed → src/data/heroImages.gen.js\n`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
